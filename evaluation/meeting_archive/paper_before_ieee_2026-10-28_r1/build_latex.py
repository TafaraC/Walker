"""Build an editable LaTeX package from the canonical Markdown paper draft.

Supports the specific headings, citations, figure blocks and table in this draft.
Does not compile TeX. Re-running overwrites main.tex; edit the Markdown source.
"""
import re
import shutil
from pathlib import Path

HERE=Path(__file__).resolve().parent
SOURCE=HERE.parent/'FINAL_PAPER_DRAFT.md'

def escape(s):
    trans={'–':'--','—':'---','−':'-','→':r'$\rightarrow$',
           '×':r'$\times$','²':r'$^2$','⁵':r'$^5$','⁶':r'$^6$',
           '“':'``','”':"''",'’':"'"}
    s=''.join({'&':r'\&','%':r'\%','_':r'\_','#':r'\#',
               '$':r'\$','{':r'\{','}':r'\}'}.get(c,c) for c in s)
    for a,b in trans.items():s=s.replace(a,b)
    s=re.sub(r'\[@([a-z0-9]+)\]',r'\\citep{\1}',s)
    s=re.sub(r'\*\*(.+?)\*\*',r'\\textbf{\1}',s)
    return s

def build():
    raw=re.sub(r'<!--.*?-->','',SOURCE.read_text(),flags=re.S)
    blocks=raw.strip().split('\n\n')
    title=blocks.pop(0).lstrip('# ')
    out=[r'''% Generated by build_latex.py from ../FINAL_PAPER_DRAFT.md.
% Edit the Markdown source, or stop regenerating if editing this file directly.
\documentclass[10pt,a4paper,twocolumn]{article}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{lmodern}
\usepackage[margin=19mm,columnsep=6mm]{geometry}
\usepackage{microtype,graphicx,booktabs,tabularx,amsmath}
\usepackage[numbers,sort&compress]{natbib}
\usepackage[colorlinks=true,allcolors=blue]{hyperref}
\graphicspath{{figures/}}
\setlength{\emergencystretch}{2em}
\setlength{\textfloatsep}{10pt}
\setlength{\dbltextfloatsep}{10pt}
\renewcommand{\topfraction}{0.95}
\renewcommand{\dbltopfraction}{0.95}
\renewcommand{\textfraction}{0.05}
\title{'''+escape(title)+r'''}
\author{Author and institution to be supplied}
\date{Working draft, 28 October 2026}
\begin{document}
\maketitle
''']
    abstract=False
    for b in blocks:
        b=b.strip()
        if not b:continue
        if b=='## Abstract':out.append(r'\begin{abstract}');abstract=True;continue
        if b.startswith('## ') and abstract:
            out.append(r'\end{abstract}');abstract=False
        if b.startswith('### '):
            out.append(r'\subsection{'+escape(re.sub(r'^\d+(?:\.\d+)*\.?\s*','',b[4:]))+'}')
        elif b.startswith('## '):
            heading=re.sub(r'^\d+\.\s*','',b[3:])
            out.append(r'\section'+('*' if heading=='Data and reproducibility' else '')+'{'+escape(heading)+'}')
        elif b.startswith('!['):
            match=re.fullmatch(r'!\[(.*?)\]\((.*?)\)',b,re.S)
            assert match,b
            caption,path=match.groups();p=(SOURCE.parent/path).with_suffix('.pdf')
            assert p.exists(),p
            (HERE/'figures').mkdir(exist_ok=True)
            shutil.copyfile(p,HERE/'figures'/p.name)
            caption=re.sub(r'^Figure \d+\.\s*','',caption)
            out.append(r'\begin{figure*}[t]\centering'+'\n'+
                       r'\includegraphics[width=\textwidth]{'+p.name+'}\n'+
                       r'\caption{'+escape(caption)+'}\n'+r'\label{fig:'+p.stem+'}\n'+r'\end{figure*}')
        elif b.startswith('|'):
            rows=[r.strip().strip('|').split('|') for r in b.splitlines()]
            table=[r'\begin{table*}[t]\centering\small'+'\n'+
                       r'\caption{Initial allocations; data, interactions and fitting are different resources.}'+'\n'+
                       r'\begin{tabularx}{\textwidth}{lXX}\toprule']
            for i,row in enumerate(rows):
                if i==1:table.append(r'\midrule');continue
                table.append(' & '.join(escape(c.strip()) for c in row)+r' \\')
            table.append(r'\bottomrule\end{tabularx}\end{table*}')
            out.append('\n'.join(table))
        else:out.append(escape(' '.join(b.splitlines())))
    out.append(r'''\label{bodyend}
\clearpage
% References excluded from the target eight-page body limit.
\bibliographystyle{plainnat}
\bibliography{references}
\end{document}
''')
    result='\n\n'.join(out)
    assert result.count(r'\begin{abstract}')==result.count(r'\end{abstract}')==1
    keys=set(re.findall(r'\\citep\{([^}]+)\}',result))
    bib=(HERE/'references.bib').read_text()
    assert keys<=set(re.findall(r'@\w+\{([^,]+),',bib)),keys
    (HERE/'main.tex').write_text(result)
    print('Built main.tex; copied six vector figures; checked',len(keys),'citation keys.')

if __name__=='__main__':build()
